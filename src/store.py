"""Persistent status, inbox/effect deduplication, and transactional outbox."""
from contextlib import contextmanager
import json
import sqlite3
import time
from pathlib import Path
from uuid import uuid4


class KeyConflict(Exception):
    pass


class Store:
    def __init__(self, path):
        self.path = str(path)

    @contextmanager
    def db(self):
        db = sqlite3.connect(self.path, timeout=5)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys=ON")
        try:
            with db:
                yield db
        finally:
            db.close()

    def init(self):
        Path(self.path).parent.mkdir(parents=True, exist_ok=True)
        with self.db() as db:
            db.execute("PRAGMA journal_mode=WAL")
            db.executescript("""
                CREATE TABLE IF NOT EXISTS jobs (
                    id TEXT PRIMARY KEY,
                    request_key TEXT UNIQUE NOT NULL,
                    payload TEXT NOT NULL,
                    status TEXT NOT NULL,
                    attempts INTEGER NOT NULL DEFAULT 0,
                    error TEXT,
                    created_at REAL NOT NULL,
                    updated_at REAL NOT NULL
                );
                CREATE TABLE IF NOT EXISTS outbox (
                    job_id TEXT PRIMARY KEY REFERENCES jobs(id),
                    sent INTEGER NOT NULL DEFAULT 0
                );
                CREATE TABLE IF NOT EXISTS reports (
                    job_id TEXT PRIMARY KEY REFERENCES jobs(id),
                    content TEXT NOT NULL
                );
            """)

    def create(self, payload, key):
        encoded = json.dumps(payload, sort_keys=True)
        with self.db() as db:
            db.execute("BEGIN IMMEDIATE")
            row = db.execute("SELECT * FROM jobs WHERE request_key=?", (key,)).fetchone()
            if row:
                if row["payload"] != encoded:
                    raise KeyConflict()
                return row["id"]
            id_ = str(uuid4())
            now = time.time()
            db.execute("INSERT INTO jobs VALUES (?,?,?,'queued',0,NULL,?,?)",
                       (id_, key, encoded, now, now))
            db.execute("INSERT INTO outbox(job_id) VALUES (?)", (id_,))
            return id_

    def get(self, id_):
        with self.db() as db:
            row = db.execute("SELECT * FROM jobs WHERE id=?", (id_,)).fetchone()
            if not row:
                return None
            job = dict(row)
            job["payload"] = json.loads(job["payload"])
            report = db.execute("SELECT content FROM reports WHERE job_id=?", (id_,)).fetchone()
            job["result"] = json.loads(report[0]) if report else None
            job.pop("request_key")
            return job

    def recent(self):
        with self.db() as db:
            ids = [r[0] for r in db.execute("SELECT id FROM jobs ORDER BY created_at DESC LIMIT 50")]
        return [self.get(id_) for id_ in ids]

    def pending(self):
        with self.db() as db:
            return [r[0] for r in db.execute("SELECT job_id FROM outbox WHERE sent=0 LIMIT 20")]

    def unsent(self, id_):
        with self.db() as db:
            row = db.execute("SELECT sent FROM outbox WHERE job_id=?", (id_,)).fetchone()
            return bool(row and not row[0])

    def sent(self, id_):
        with self.db() as db:
            db.execute("UPDATE outbox SET sent=1 WHERE job_id=?", (id_,))

    def start(self, id_):
        with self.db() as db:
            db.execute("BEGIN IMMEDIATE")
            row = db.execute("SELECT status FROM jobs WHERE id=?", (id_,)).fetchone()
            if not row:
                raise ValueError("Unknown job")
            if row[0] == "completed":
                return False
            if row[0] == "failed":
                return None
            db.execute("UPDATE jobs SET status='processing',attempts=attempts+1,updated_at=? WHERE id=?",
                       (time.time(), id_))
            return True

    def complete(self, id_):
        # The simulated business effect and terminal status commit together.
        # PK(job_id) prevents duplicate reports even after commit-before-ACK crashes.
        with self.db() as db:
            db.execute("BEGIN IMMEDIATE")
            row = db.execute("SELECT payload FROM jobs WHERE id=?", (id_,)).fetchone()
            if not row:
                raise ValueError("Unknown job")
            payload = json.loads(row[0])
            result = {"title": payload["title"], "summary": "Report generated by the background worker."}
            db.execute("INSERT OR IGNORE INTO reports VALUES (?,?)",
                       (id_, json.dumps(result)))
            db.execute("UPDATE jobs SET status='completed',error=NULL,updated_at=? WHERE id=?",
                       (time.time(), id_))

    def problem(self, id_, error, terminal):
        with self.db() as db:
            db.execute("""UPDATE jobs SET status=?,error=?,updated_at=?
                          WHERE id=? AND status!='completed'""",
                       ("failed" if terminal else "queued", error, time.time(), id_))

    def effect_count(self, id_):
        with self.db() as db:
            return db.execute("SELECT count(*) FROM reports WHERE job_id=?", (id_,)).fetchone()[0]
